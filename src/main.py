@app.post(
    "/v1/medical/analyze",
    response_model=ImageAnalysisResponse,
    tags=["Medical"],
    summary="Medical image analysis",
    description="Analyze medical images (X-rays, CT, MRI, pathology, dermatology) with AI.",
)
async def analyze_image(
    request: ImageAnalysisRequest,
    api_key: APIKeyDep,
    service: MedGemmaService = Depends(get_medgemma_service),
) -> ImageAnalysisResponse:
    """
    Analyze medical images with MedGemma.

    Supports multiple modalities:
    - Radiology: X-ray, CT, MRI
    - Pathology: Histopathology slides
    - Dermatology: Skin lesions, conditions
    - Ophthalmology: Retinal scans
    - Clinical photography

    Images should be base64-encoded or provided as data URLs.
    Maximum 4 images per request.
    """
    if not service.is_loaded:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail={"error": {"code": "model_not_loaded", "message": "Model is still loading."}},
        )

    try:
        # Build prompt with clinical context
        prompt_parts = []

        if request.image_modality:
            prompt_parts.append(f"[Image Type: {request.image_modality}]")

        if request.clinical_context:
            prompt_parts.append(f"[Clinical Context: {request.clinical_context}]")

        prompt_parts.append(request.query)

        if request.structured_output:
            prompt_parts.append(
                "\nPlease provide your analysis in a structured format with: "
                "1) Observations, 2) Findings, 3) Assessment, 4) Recommendations."
            )

        full_prompt = "\n\n".join(prompt_parts)

        # Generate response with images
        result = service.generate(
            prompt=full_prompt,
            system_prompt=request.system_prompt,
            images=request.images,
            max_new_tokens=request.max_tokens,
            temperature=request.temperature,
        )

        # Parse structured findings if requested
        findings = None
        if request.structured_output:
            # Simple parsing - extract numbered items
            lines = result["response"].split("\n")
            findings = [
                line.strip()
                for line in lines
                if line.strip() and (
                    line.strip()[0].isdigit()
                    or line.strip().startswith("-")
                    or line.strip().startswith("•")
                )
            ]

        return ImageAnalysisResponse(
            analysis=result["response"],
            findings=findings,
            usage=UsageInfo(**result["usage"]),
            model=result["model"],
            image_count=len(request.images),
        )

    except ValueError as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"error": {"code": "invalid_request", "message": str(e)}},
        )
    except Exception as e:
        logger.exception("Error in image analysis")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail={"error": {"code": "internal_error", "message": str(e)}},
        )


