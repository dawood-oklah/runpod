@app.post(
    "/v1/medical/report",
    response_model=MedicalReportResponse,
    tags=["Medical"],
    summary="Generate medical report",
    description="Generate structured medical reports from images (radiology, pathology, etc.).",
)
async def generate_report(
    request: MedicalReportRequest,
    api_key: APIKeyDep,
    service: MedGemmaService = Depends(get_medgemma_service),
) -> MedicalReportResponse:
    """
    Generate structured medical reports from images.

    Creates comprehensive reports following medical documentation standards.
    Includes:
    - Examination findings
    - Impressions
    - Recommendations
    - Differential diagnoses (when applicable)

    Supports radiology, pathology, dermatology, and ophthalmology reports.
    """
    if not service.is_loaded:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail={"error": {"code": "model_not_loaded", "message": "Model is still loading."}},
        )

    try:
        # Build report prompt based on report type
        report_prompts = {
            "radiology": """Generate a comprehensive radiology report for the provided image(s).
Include the following sections:
1. EXAMINATION: Type of imaging study
2. CLINICAL INDICATION: {indication}
3. COMPARISON: {comparison}
4. TECHNIQUE: Brief description if relevant
5. FINDINGS: Detailed systematic description of findings
6. IMPRESSION: Summary of key findings
7. RECOMMENDATIONS: Follow-up recommendations if any""",

            "pathology": """Generate a pathology report for the provided image(s).
Include the following sections:
1. SPECIMEN: Description of specimen
2. CLINICAL HISTORY: {indication}
3. GROSS DESCRIPTION: Macroscopic findings (if visible)
4. MICROSCOPIC DESCRIPTION: Detailed histological findings
5. DIAGNOSIS: Pathological diagnosis
6. COMMENTS: Additional relevant information
7. RECOMMENDATIONS: Further testing or follow-up if needed""",

            "dermatology": """Generate a dermatology assessment for the provided image(s).
Include the following sections:
1. CLINICAL PRESENTATION: Description of the lesion/condition
2. PATIENT HISTORY: {indication}
3. MORPHOLOGY: Shape, size, color, texture, borders
4. DISTRIBUTION: Location and pattern
5. DIFFERENTIAL DIAGNOSIS: List of possible diagnoses
6. ASSESSMENT: Most likely diagnosis with reasoning
7. RECOMMENDATIONS: Treatment options or further evaluation needed""",

            "ophthalmology": """Generate an ophthalmology report for the provided image(s).
Include the following sections:
1. EXAMINATION TYPE: Type of imaging (fundus, OCT, etc.)
2. CLINICAL INDICATION: {indication}
3. FINDINGS - RIGHT EYE (OD): Detailed findings
4. FINDINGS - LEFT EYE (OS): Detailed findings (if applicable)
5. ASSESSMENT: Interpretation of findings
6. RECOMMENDATIONS: Follow-up or treatment recommendations""",

            "general": """Generate a comprehensive medical image analysis report.
Include the following sections:
1. IMAGE TYPE: Description of the medical image
2. CLINICAL CONTEXT: {indication}
3. OBSERVATIONS: Systematic description of what is visible
4. FINDINGS: Key abnormalities or notable features
5. ASSESSMENT: Clinical interpretation
6. RECOMMENDATIONS: Suggested next steps or follow-up"""
        }

        # Get template and fill in details
        template = report_prompts.get(request.report_type, report_prompts["general"])
        prompt = template.format(
            indication=request.clinical_indication or "Not provided",
            comparison=request.comparison_studies or "None available",
        )

        # Add patient info if provided
        if request.patient_info:
            prompt = f"PATIENT INFORMATION: {request.patient_info}\n\n{prompt}"

        # Build specialized system prompt for report generation
        system_prompt = f"""You are an expert medical professional generating a formal {request.report_type} report.
Follow standard medical documentation practices. Be thorough, precise, and professional.
Always note limitations in image quality or visibility that may affect interpretation.
Include appropriate medical terminology while remaining clear."""

        # Generate report
        result = service.generate(
            prompt=prompt,
            system_prompt=system_prompt,
            images=request.images,
            max_new_tokens=request.max_tokens,
            temperature=0.3,  # Lower temperature for more consistent reports
        )

        # Try to parse sections from the report
        sections = {}
        current_section = None
        current_content = []

        for line in result["response"].split("\n"):
            line = line.strip()
            # Check for section headers (usually in caps or numbered)
            if line.endswith(":") and len(line) < 50:
                if current_section:
                    sections[current_section] = "\n".join(current_content).strip()
                current_section = line[:-1]
                current_content = []
            elif line.startswith(tuple("0123456789")) and "." in line[:3]:
                # Numbered section
                if current_section:
                    sections[current_section] = "\n".join(current_content).strip()
                parts = line.split(".", 1)
                if len(parts) > 1:
                    current_section = parts[1].strip().rstrip(":")
                    current_content = []
            else:
                current_content.append(line)

        if current_section:
            sections[current_section] = "\n".join(current_content).strip()

        return MedicalReportResponse(
            report=result["response"],
            report_type=request.report_type,
            sections=sections if sections else None,
            usage=UsageInfo(**result["usage"]),
            model=result["model"],
        )

    except ValueError as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"error": {"code": "invalid_request", "message": str(e)}},
        )
    except Exception as e:
        logger.exception("Error in report generation")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail={"error": {"code": "internal_error", "message": str(e)}},
        )


