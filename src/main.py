@app.post(
    "/v1/medical/query",
    response_model=MedicalQueryResponse,
    tags=["Medical"],
    summary="Text-only medical query",
    description="Submit medical questions or clinical cases for AI analysis. Optimized for long prompts (up to 10K tokens).",
)
async def medical_query(
    request: MedicalQueryRequest,
    api_key: APIKeyDep,
    service: MedGemmaService = Depends(get_medgemma_service),
) -> MedicalQueryResponse:
    """
    Process text-only medical queries.

    Ideal for:
    - Clinical case analysis
    - Differential diagnosis
    - Treatment recommendations
    - Medical literature questions
    - Patient history analysis

    Supports up to ~10,000 tokens in the query.
    """
    if not service.is_loaded:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail={"error": {"code": "model_not_loaded", "message": "Model is still loading."}},
        )

    try:
        # Convert conversation history if provided
        history = None
        if request.conversation_history:
            history = [
                {"role": msg.role, "content": msg.content}
                for msg in request.conversation_history
            ]

        # Generate response
        result = service.generate(
            prompt=request.query,
            system_prompt=request.system_prompt,
            conversation_history=history,
            max_new_tokens=request.max_tokens,
            temperature=request.temperature,
        )

        # Add disclaimer if requested
        disclaimer = MEDICAL_DISCLAIMER if request.include_disclaimer else None

        return MedicalQueryResponse(
            response=result["response"],
            usage=UsageInfo(**result["usage"]),
            model=result["model"],
            disclaimer=disclaimer,
        )

    except ValueError as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"error": {"code": "invalid_request", "message": str(e)}},
        )
    except Exception as e:
        logger.exception("Error in medical query")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail={"error": {"code": "internal_error", "message": str(e)}},
        )


