@app.post(
    "/v1/chat/completions",
    response_model=ChatCompletionResponse,
    tags=["Chat"],
    summary="OpenAI-compatible chat completions",
    description="Generate chat completions using MedGemma. Compatible with OpenAI client libraries.",
)
async def chat_completions(
    request: ChatCompletionRequest,
    api_key: APIKeyDep,
    service: MedGemmaService = Depends(get_medgemma_service),
) -> ChatCompletionResponse:
    """
    Generate chat completion responses.

    Follows OpenAI API format for compatibility with existing tools and libraries.
    Supports multi-turn conversations with system prompts.

    Note: Streaming is not yet supported.
    """
    if not service.is_loaded:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail={"error": {"code": "model_not_loaded", "message": "Model is still loading. Please try again later."}},
        )

    if request.stream:
        raise HTTPException(
            status_code=status.HTTP_501_NOT_IMPLEMENTED,
            detail={"error": {"code": "streaming_not_supported", "message": "Streaming is not yet supported."}},
        )

    try:
        # Extract system prompt and conversation history
        system_prompt = None
        conversation_history = []
        user_prompt = ""

        for msg in request.messages:
            if msg.role == "system":
                system_prompt = msg.content
            elif msg.role == "user":
                # Last user message is the prompt
                user_prompt = msg.content
            else:
                conversation_history.append({"role": msg.role, "content": msg.content})

        # Generate response
        result = service.generate(
            prompt=user_prompt,
            system_prompt=system_prompt,
            conversation_history=conversation_history if conversation_history else None,
            max_new_tokens=request.max_tokens,
            temperature=request.temperature,
            top_p=request.top_p,
            top_k=request.top_k,
        )

        # Format as OpenAI response
        return ChatCompletionResponse(
            id=f"chatcmpl-{uuid.uuid4().hex[:8]}",
            model=result["model"],
            choices=[
                Choice(
                    index=0,
                    message={"role": "assistant", "content": result["response"]},
                    finish_reason="stop",
                )
            ],
            usage=UsageInfo(**result["usage"]),
        )

    except ValueError as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={"error": {"code": "invalid_request", "message": str(e)}},
        )
    except Exception as e:
        logger.exception("Error in chat completion")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail={"error": {"code": "internal_error", "message": str(e)}},
        )


